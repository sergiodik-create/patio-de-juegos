/* Texto del cuento con cada palabra en su propio span: se resalta mientras se lee y se puede tocar para oírla. */
function wordsHTML(txt){let html='',i=0;
  for(const m of txt.matchAll(/\S+/g)){html+=esc(txt.slice(i,m.index))+`<span class="w" data-s="${m.index}" data-e="${m.index+m[0].length}">${esc(m[0])}</span>`;i=m.index+m[0].length;}
  return html+esc(txt.slice(i));}
function leer(g){
  const t=g.tale;let i=0,auto=false,tok=0;
  const draw=()=>{const [pic,txt]=t.pages[i];
    $('#stage').innerHTML=`<div class="screen"><div class="book"><div class="bpic" aria-hidden="true">${pic}</div><p class="btext" id="btext">${wordsHTML(txt)}</p><p class="bpage">${i+1} / ${t.pages.length}</p></div>
      <div class="row"><button class="pill" id="bprev" ${i===0?'disabled':''}>${_('◀ Atrás')}</button><button class="pill" id="bread">${_('🔊 Escuchar')}</button><button class="pill" id="bnext">${i===t.pages.length-1?_('Otro cuento'):_('Siguiente ▶')}</button></div>
      <div class="row"><button class="pill" id="bauto" aria-pressed="${auto}">${auto?_('⏸ Parar'):_('▶ Leer el cuento entero')}</button></div>
      <p class="tip">${_('Toca una palabra para oírla.')}</p></div>`;
    $('#bprev').onclick=()=>{auto=false;tok++;if(i>0){i--;draw();read();}};
    $('#bnext').onclick=()=>{auto=false;tok++;if(i<t.pages.length-1){i++;draw();read();}else goHome();};
    $('#bread').onclick=()=>{auto=false;tok++;draw();read();};
    $('#bauto').onclick=()=>{auto=!auto;tok++;draw();if(auto)read();else stopVoice();};
    $('#btext').onclick=e=>{const w=e.target.closest('.w');if(!w)return;auto=false;tok++;mark(w);say(w.textContent.replace(/[¡!¿?.,;:«»"()…]/g,''));};};
  const mark=w=>{document.querySelectorAll('#btext .hl').forEach(x=>x.classList.remove('hl'));if(w)w.classList.add('hl');};
  const read=()=>{const my=++tok,pre=i===0?t.name+'. ':'',txt=pre+t.pages[i][1];
    sayThen(txt,()=>{mark(null);if(my!==tok||cur!==g||!auto)return;if(i<t.pages.length-1){later(()=>{if(my!==tok||cur!==g||!auto)return;i++;draw();read();},800);}else{auto=false;draw();star();confetti();}},
      ci=>{if(my!==tok)return;const k=ci-pre.length;const w=[...document.querySelectorAll('#btext .w')].find(x=>k>=+x.dataset.s&&k<+x.dataset.e);if(w)mark(w);});};
  draw();read();
}

